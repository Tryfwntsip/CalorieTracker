export type ProductionFoodSeed = Nutrients & {
  id: string;
  externalId: string;
  name: string;
  nameEl: string;
  servingName: string;
  servingNameEl: string;
  servingGrams: number;
  isLiquid: boolean;
};

export const productionFoodSeeds: readonly ProductionFoodSeed[] = groups.flatMap(
  ({ items, ...nutrients }, groupIndex) =>
    items.map(
      (
        [
          name,
          nameEl,
          servingName = 'serving',
          servingNameEl = 'μερίδα',
          servingGrams = 100,
          isLiquid = false,
        ],
        itemIndex,
      ) => {
        const sequence = groupIndex * 10 + itemIndex + 1;
        const key = String(sequence).padStart(3, '0');
        return {
          ...nutrients,
          id: `greek-food-${key}`,
          externalId: `greek-${key}`,
          name,
          nameEl,
          servingName,
          servingNameEl,
          servingGrams,
          isLiquid,
        };
      },
    ),
);
